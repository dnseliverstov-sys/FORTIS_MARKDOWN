export function markdownToJiraDescription(markdown: string): string {
  return markdown
    .replace(/^######\s+/gmu, 'h6. ').replace(/^#####\s+/gmu, 'h5. ').replace(/^####\s+/gmu, 'h4. ')
    .replace(/^###\s+/gmu, 'h3. ').replace(/^##\s+/gmu, 'h2. ').replace(/^#\s+/gmu, 'h1. ')
    .replace(/\*\*([^*]+)\*\*/gu, '*$1*')
    .replace(/~~([^~]+)~~/gu, '-$1-')
    .replace(/^\s*[-*+]\s+\[[ xX]\]\s+/gmu, '* ')
    .replace(/^\s*[-*+]\s+/gmu, '* ')
    .replace(/^\s*>\s?\[!\w+\]\s*$/gmu, '')
    .replace(/^\s*>\s?/gmu, 'bq. ')
    .replace(/```(\w*)\n([\s\S]*?)```/gu, (_match, lang: string, code: string) => `{code${lang ? `:${lang}` : ''}}\n${code}{code}`)
    .replace(/\[([^\]]+)\]\(([^)]+)\)/gu, '[$1|$2]');
}
